// kohane-decoder CLI - the Rust verification brick.
//
//   kohane-decoder adpcm <in.raw> <out.kba> [sampleRate]
//   kohane-decoder flac  <in.raw> <out.flac> <sampleRate> [channels]
//   kohane-decoder sf2   <file.sf2>        -> receipt JSON on stdout
//   kohane-decoder fxp   <file.fxp|.fxb>   -> receipt JSON on stdout
//   kohane-decoder lm4   <file.txt>        -> receipt JSON on stdout
//   kohane-decoder kb write <kbs|kbw|kbv|kbm> <out.file> [params.json|-]
//   kohane-decoder kb read  <kbs|kbw|kbv|kbm> <file>   -> receipt JSON on stdout
//   kohane-decoder capabilities             -> capability array on stdout
//   kohane-decoder registry                 -> tool-surface map on stdout
//
// The input is raw 16-bit little-endian PCM (generated by the JS side, so both languages encode
// the same bytes and the cross-check is byte-exact). The KBA1 container is tier 2 (ADPCM) and the
// FLAC stream is byte-identical with deps/decoders/flac-encoder.mjs.
use kohane_decoder::parsers::{fxp, kbmedia, lm4, sf2};
use kohane_decoder::{adpcm, flac, kba, registry};
use std::env;
use std::fs;
use std::io::Read;
use std::process::ExitCode;

fn kba_header(tier: u8, sample_rate: u32, channels: u16, frames: u32) -> Vec<u8> {
    let mut h = Vec::with_capacity(16);
    h.extend_from_slice(b"KBA1");
    h.push(1); // version
    h.push(tier);
    h.extend_from_slice(&sample_rate.to_le_bytes());
    h.extend_from_slice(&channels.to_le_bytes());
    h.extend_from_slice(&frames.to_le_bytes());
    h
}

fn cmd_adpcm(input: &str, output: &str, sample_rate: u32) -> Result<(), String> {
    let raw = fs::read(input).map_err(|e| format!("cannot read {input}: {e}"))?;
    if raw.len() % 2 != 0 {
        return Err("the raw input has an odd byte count (not 16-bit PCM)".into());
    }
    let pcm: Vec<i16> = raw
        .chunks_exact(2)
        .map(|c| i16::from_le_bytes([c[0], c[1]]))
        .collect();
    let frames = pcm.len() as u32;
    let body = adpcm::adpcm_encode(&pcm);
    let mut out = kba_header(2, sample_rate, 1, frames);
    out.extend_from_slice(&body);
    fs::write(output, &out).map_err(|e| format!("cannot write {output}: {e}"))?;
    println!("encoded {frames} frames into {output} ({} bytes)", out.len());
    Ok(())
}

fn cmd_flac(input: &str, output: &str, sample_rate: u32, channels: u16) -> Result<(), String> {
    let raw = fs::read(input).map_err(|e| format!("cannot read {input}: {e}"))?;
    if raw.len() % 2 != 0 {
        return Err("the raw input has an odd byte count (not 16-bit PCM)".into());
    }
    let pcm: Vec<i16> = raw
        .chunks_exact(2)
        .map(|c| i16::from_le_bytes([c[0], c[1]]))
        .collect();
    let out = flac::encode_flac(&pcm, sample_rate, channels, "kohane-index-desuno");
    fs::write(output, &out).map_err(|e| format!("cannot write {output}: {e}"))?;
    println!("encoded {} frames into {output} ({} bytes)", pcm.len() / channels as usize, out.len());
    Ok(())
}

fn main() -> ExitCode {
    let args: Vec<String> = env::args().collect();
    match args.get(1).map(String::as_str) {
        Some("adpcm") => {
            let (Some(input), Some(output)) = (args.get(2), args.get(3)) else {
                eprintln!("usage: kohane-decoder adpcm <in.raw> <out.kba> [sampleRate]");
                return ExitCode::from(2);
            };
            let rate: u32 = args.get(4).and_then(|s| s.parse().ok()).unwrap_or(44100);
            match cmd_adpcm(input, output, rate) {
                Ok(()) => ExitCode::SUCCESS,
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        Some("flac") => {
            let (Some(input), Some(output), Some(rate_arg)) = (args.get(2), args.get(3), args.get(4)) else {
                eprintln!("usage: kohane-decoder flac <in.raw> <out.flac> <sampleRate> [channels]");
                return ExitCode::from(2);
            };
            let rate: u32 = match rate_arg.parse() {
                Ok(r) if r > 0 => r,
                _ => {
                    eprintln!("sampleRate must be a positive number");
                    return ExitCode::from(2);
                }
            };
            let channels: u16 = args.get(5).and_then(|s| s.parse().ok()).unwrap_or(1);
            match cmd_flac(input, output, rate, channels) {
                Ok(()) => ExitCode::SUCCESS,
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        Some("sf2") => {
            let Some(input) = args.get(2) else {
                eprintln!("usage: kohane-decoder sf2 <file.sf2>");
                return ExitCode::from(2);
            };
            match sf2::read_sf2(input) {
                Ok(font) => {
                    println!("{}", font.to_json().render());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        Some("fxp") => {
            let Some(input) = args.get(2) else {
                eprintln!("usage: kohane-decoder fxp <file.fxp>");
                return ExitCode::from(2);
            };
            match fxp::read_fxp(input) {
                Ok(preset) => {
                    println!("{}", preset.to_json().render());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        Some("lm4") => {
            let Some(input) = args.get(2) else {
                eprintln!("usage: kohane-decoder lm4 <file.txt>");
                return ExitCode::from(2);
            };
            match lm4::read_lm4_kit(input) {
                Ok(kit) => {
                    println!("{}", kit.to_json().render());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        Some("kb") => cmd_kb(&args),
        Some("kba") => cmd_kba(&args),
        Some("capabilities") => {
            println!("{}", kbmedia::capabilities().render());
            ExitCode::SUCCESS
        }
        Some("registry") => {
            println!("{}", registry::render());
            ExitCode::SUCCESS
        }
        _ => {
            eprintln!("usage: kohane-decoder adpcm <in.raw> <out.kba> [sampleRate]");
            eprintln!("       kohane-decoder flac  <in.raw> <out.flac> <sampleRate> [channels]");
            eprintln!("       kohane-decoder sf2   <file.sf2>");
            eprintln!("       kohane-decoder fxp   <file.fxp>");
            eprintln!("       kohane-decoder lm4   <file.txt>");
            eprintln!("       kohane-decoder kb write <kbs|kbw|kbv|kbm> <out.file> [params.json|-]");
            eprintln!("       kohane-decoder kb read  <kbs|kbw|kbv|kbm> <file>");
            eprintln!("       kohane-decoder capabilities");
            eprintln!("       kohane-decoder registry");
            eprintln!("       kohane-decoder kba encode <in.raw> <out.kba> <0|1|2|raw|lossless|adpcm> [sampleRate] [channels]");
            eprintln!("       kohane-decoder kba decode <file.kba>");
            eprintln!("       kohane-decoder kba stats <file.kba>");
            ExitCode::from(2)
        }
    }
}

fn cmd_kb(args: &[String]) -> ExitCode {
    let (Some(verb), Some(kind), Some(target)) = (args.get(2), args.get(3), args.get(4)) else {
        eprintln!("usage: kohane-decoder kb write <kbs|kbw|kbv|kbm> <out.file> [params.json|-]");
        eprintln!("       kohane-decoder kb read  <kbs|kbw|kbv|kbm> <file>");
        return ExitCode::from(2);
    };
    let kind = kind.as_str();
    if !["kbs", "kbw", "kbv", "kbm"].contains(&kind) {
        eprintln!("kind must be one of kbs, kbw, kbv, kbm");
        return ExitCode::from(2);
    }
    match verb.as_str() {
        "write" => {
            let params_arg = args.get(5).map(String::as_str).unwrap_or("-");
            let text = match params_arg {
                "-" => {
                    let mut s = String::new();
                    if let Err(e) = std::io::stdin().read_to_string(&mut s) {
                        eprintln!("cannot read params from stdin: {e}");
                        return ExitCode::from(1);
                    }
                    s
                }
                file => match fs::read_to_string(file) {
                    Ok(s) => s,
                    Err(e) => {
                        eprintln!("cannot read {file}: {e}");
                        return ExitCode::from(1);
                    }
                },
            };
            let params = match kohane_decoder::json::parse(&text) {
                Ok(v) => v,
                Err(e) => {
                    eprintln!("{e}");
                    return ExitCode::from(1);
                }
            };
            let bytes = match kind {
                "kbs" => kbmedia::write_kbs(&params),
                "kbw" => kbmedia::write_kbw(&params),
                "kbv" => kbmedia::write_kbv(&params),
                _ => kbmedia::write_kbm(&params),
            };
            match fs::write(target, &bytes) {
                Ok(()) => {
                    println!("wrote {} bytes to {target}", bytes.len());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("cannot write {target}: {e}");
                    ExitCode::from(1)
                }
            }
        }
        "read" => {
            let buf = match fs::read(target) {
                Ok(b) => b,
                Err(e) => {
                    eprintln!("cannot read {target}: {e}");
                    return ExitCode::from(1);
                }
            };
            let receipt = match kind {
                "kbs" => kbmedia::read_kbs(&buf),
                "kbw" => kbmedia::read_kbw(&buf),
                "kbv" => kbmedia::read_kbv(&buf),
                _ => kbmedia::read_kbm(&buf),
            };
            match receipt {
                Ok(r) => {
                    println!("{}", r.render());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        _ => {
            eprintln!("usage: kohane-decoder kb write <kbs|kbw|kbv|kbm> <out.file> [params.json|-]");
            eprintln!("       kohane-decoder kb read  <kbs|kbw|kbv|kbm> <file>");
            ExitCode::from(2)
        }
    }
}

fn cmd_kba(args: &[String]) -> ExitCode {
    let Some(verb) = args.get(2).map(String::as_str) else {
        eprintln!("usage: kohane-decoder kba encode <in.raw> <out.kba> <0|1|2|raw|lossless|adpcm> [sampleRate] [channels]");
        eprintln!("       kohane-decoder kba decode <file.kba>");
        eprintln!("       kohane-decoder kba stats <file.kba>");
        return ExitCode::from(2);
    };
    let tier_of = |s: &str| -> Option<u8> {
        match s {
            "0" | "raw" => Some(0),
            "1" | "lossless" => Some(1),
            "2" | "adpcm" => Some(2),
            _ => None,
        }
    };
    match verb {
        "encode" => {
            let (Some(input), Some(output), Some(tier_arg)) = (args.get(3), args.get(4), args.get(5)) else {
                eprintln!("usage: kohane-decoder kba encode <in.raw> <out.kba> <0|1|2|raw|lossless|adpcm> [sampleRate] [channels]");
                return ExitCode::from(2);
            };
            let Some(tier) = tier_of(tier_arg) else {
                eprintln!("tier must be one of 0|raw, 1|lossless, 2|adpcm");
                return ExitCode::from(2);
            };
            let raw = match fs::read(input) {
                Ok(b) => b,
                Err(e) => {
                    eprintln!("cannot read {input}: {e}");
                    return ExitCode::from(1);
                }
            };
            if raw.len() % 2 != 0 {
                eprintln!("the raw input has an odd byte count (not 16-bit PCM)");
                return ExitCode::from(1);
            }
            let pcm: Vec<i16> = raw
                .chunks_exact(2)
                .map(|c| i16::from_le_bytes([c[0], c[1]]))
                .collect();
            let rate: u32 = args.get(6).and_then(|s| s.parse().ok()).unwrap_or(44100);
            let channels: u16 = args.get(7).and_then(|s| s.parse().ok()).unwrap_or(1);
            match kba::encode_kba(&pcm, tier, rate, channels) {
                Ok(bytes) => match fs::write(output, &bytes) {
                    Ok(()) => {
                        println!("encoded {} frames into {output} ({} bytes)", pcm.len(), bytes.len());
                        ExitCode::SUCCESS
                    }
                    Err(e) => {
                        eprintln!("cannot write {output}: {e}");
                        ExitCode::from(1)
                    }
                },
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        "decode" => {
            let Some(target) = args.get(3) else {
                eprintln!("usage: kohane-decoder kba decode <file.kba>");
                return ExitCode::from(2);
            };
            let buf = match fs::read(target) {
                Ok(b) => b,
                Err(e) => {
                    eprintln!("cannot read {target}: {e}");
                    return ExitCode::from(1);
                }
            };
            match kba::decode_kba(&buf) {
                Ok(r) => {
                    println!("{}", r.to_json().render());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        "stats" => {
            let Some(target) = args.get(3) else {
                eprintln!("usage: kohane-decoder kba stats <file.kba>");
                return ExitCode::from(2);
            };
            let buf = match fs::read(target) {
                Ok(b) => b,
                Err(e) => {
                    eprintln!("cannot read {target}: {e}");
                    return ExitCode::from(1);
                }
            };
            match kba::kba_stats(&buf) {
                Ok(s) => {
                    println!("{}", s.to_json().render());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    eprintln!("{e}");
                    ExitCode::from(1)
                }
            }
        }
        _ => {
            eprintln!("usage: kohane-decoder kba encode <in.raw> <out.kba> <0|1|2|raw|lossless|adpcm> [sampleRate] [channels]");
            eprintln!("       kohane-decoder kba decode <file.kba>");
            eprintln!("       kohane-decoder kba stats <file.kba>");
            ExitCode::from(2)
        }
    }
}
